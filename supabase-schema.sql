-- WHO IS THAT? — RB Edition
-- One-time setup for the shared, self-paced leaderboard and live Top 3 board.
-- Run the entire file in Supabase SQL Editor as the project database owner.

create table if not exists public.rb_game_results (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(trim(player_name)) between 1 and 32),
  score integer not null check (score between 0 and 2900),
  correct_count integer not null check (correct_count between 0 and 29),
  total_seconds numeric(8,2) not null check (total_seconds between 0 and 435),
  created_at timestamptz not null default now()
);

alter table public.rb_game_results enable row level security;

drop policy if exists "Anyone can read RB leaderboard" on public.rb_game_results;
create policy "Anyone can read RB leaderboard"
on public.rb_game_results for select
to anon, authenticated
using (true);

drop policy if exists "Players can submit RB results" on public.rb_game_results;
create policy "Players can submit RB results"
on public.rb_game_results for insert
to anon, authenticated
with check (
  char_length(trim(player_name)) between 1 and 32
  and score between 0 and 2900
  and correct_count between 0 and 29
  and total_seconds between 0 and 435
);

grant select, insert on public.rb_game_results to anon, authenticated;
grant usage, select on sequence public.rb_game_results_id_seq to anon, authenticated;

-- Enable Postgres Changes for the live public leaderboard.
-- This block is safe to run again: it creates/adds the publication/table only when missing.
do $$
begin
  if not exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    execute 'create publication supabase_realtime';
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'rb_game_results'
  ) then
    execute 'alter publication supabase_realtime add table public.rb_game_results';
  end if;
end
$$;

